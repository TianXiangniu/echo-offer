# 0-4 等级锚点：评分前必须逐条对照，这是消除评分漂移的核心
LEVEL_ANCHORS = (
    "4 = 有具体做法，讲清了机制和原因，并主动给出取舍、代价、边界或量化结果",
    "3 = 有具体做法并联系了实际场景，但没有主动展开取舍或代价",
    "2 = 方向正确，有初步做法或具体思路，但缺少场景细节或机制解释",
    "1 = 只罗列了相关概念或孤立动作，没有任何展开",
    "0 = 概念或结论错误、答非所问，或没有任何可用内容",
)

CONFIDENCE_SEMANTICS = (
    "confidence 表示你对本次等级判断的把握：0.9 = 回答中有直接证据支撑该等级；"
    "0.6 = 部分依据靠推断；0.3 = 证据不足，等级主要靠猜。"
)

OFFTOPIC_RULE = (
    "如果合并后的回答整体与问题无关，所有 Rubric 项最高给 1 级，"
    "并在 quoted_text 中引用能说明无关的原文。"
)


def render_level_anchors() -> str:
    return "\n".join(LEVEL_ANCHORS)


